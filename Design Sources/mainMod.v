`timescale 1ns / 1ps

module mainMod(A, B, C, D, op, out, rnd_mode,done);

input  [31:0] A, B, C, D;
input         op;
input  [1:0]  rnd_mode;
output reg [31:0] out;
output reg done;

wire [7:0]  expA=A[30:23], expB=B[30:23], expC=C[30:23], expD=D[30:23];
wire        sA=A[31], sB=B[31], sC=C[31], sD=D[31];

// FIX 1: hidden bit only for normal numbers (exp != 0)
wire [23:0] mA = {(expA != 8'd0), A[22:0]};
wire [23:0] mB = {(expB != 8'd0), B[22:0]};
wire [23:0] mC = {(expC != 8'd0), C[22:0]};
wire [23:0] mD = {(expD != 8'd0), D[22:0]};

wire [47:0] pAB, pCD;
dadda d1(mA, mB, pAB);
dadda d2(mC, mD, pCD);

wire [8:0] eAB = {1'b0,expA} + {1'b0,expB};
wire [8:0] eCD = {1'b0,expC} + {1'b0,expD};

