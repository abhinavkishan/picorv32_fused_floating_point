reg [8:0]  exp_base, shift_amt, exp_out;
reg [47:0] large_p, small_p, small_sh, raw_sum, norm;
reg [48:0] sum49_;          // 49-bit for addition carry detection
reg        add_carry_;       // carry-out flag from addition
reg [48:0] n49_;             // 49-bit for rounding carry detection
reg        sign_AB, sign_CD, eff_sub, result_sign, rnd_up;
reg [7:0]  lz;
reg [22:0] mant_out;
reg        guard, round_, sticky_;
reg [47:0] sticky_mask;
reg        large_is_AB;   // track which product is large

always @(*) begin
    sign_AB = sA ^ sB;
    sign_CD = sC ^ sD;
    eff_sub = sign_AB ^ sign_CD ^ op;

    // Select large/small
    if (eAB >= eCD) begin
        large_p     = pAB;  small_p = pCD;
        exp_base    = eAB - 9'd127;
        shift_amt   = eAB - eCD;
        large_is_AB = 1'b1;
    end else begin
        large_p     = pCD;  small_p = pAB;
        exp_base    = eCD - 9'd127;
        shift_amt   = eCD - eAB;
        large_is_AB = 1'b0;
    end

    // Result sign: sign of the dominant operand in the context of the operation
    // When AB dominates: result ? ±A*B ? sign_AB regardless of op
    // When CD dominates: op=0 ? result ? +C*D ? sign_CD
    //                    op=1 ? result ? -C*D ? ~sign_CD
    if (large_is_AB)
        result_sign = sign_AB;
    else
        result_sign = op ? (~sign_CD) : sign_CD;

    // Align small product
    if (shift_amt == 9'd0) begin
        small_sh = small_p;
        guard = 1'b0;  round_ = 1'b0;  sticky_ = 1'b0;
    end else if (shift_amt >= 9'd48) begin
        small_sh = 48'd0;
        guard = 1'b0;  round_ = 1'b0;
        sticky_ = (small_p != 48'd0) ? 1'b1 : 1'b0;
    end else begin
        small_sh    = small_p >> shift_amt[5:0];
        guard       = (small_p >> (shift_amt[5:0] - 6'd1)) & 48'd1;
        round_      = (shift_amt >= 9'd2) ?
                      ((small_p >> (shift_amt[5:0] - 6'd2)) & 48'd1) : 1'b0;
        sticky_mask = (shift_amt >= 9'd2) ?
                      ((48'd1 << (shift_amt[5:0] - 6'd2)) - 48'd1) : 48'd0;
        sticky_     = (shift_amt >= 9'd2) ? (|(small_p & sticky_mask)) : 1'b0;
    end

    // Add/subtract magnitudes
    // Add or subtract (49-bit to capture carry-out on addition)
    if (eff_sub) begin
        add_carry_ = 1'b0;
        if (small_sh > large_p) begin
            raw_sum     = small_sh - large_p;
            result_sign = ~result_sign;
        end else
            raw_sum = large_p - small_sh;
    end else begin
        // Addition: use 49-bit to detect carry-out
        sum49_ = {1'b0, large_p} + {1'b0, small_sh};
        add_carry_ = sum49_[48];
        if (sum49_[48]) begin
            // Carry out: shift right 1. lz stays as leading_one(raw_sum).
            // exp gets +1 via add_carry_ in the exponent formula below.
            raw_sum = sum49_[48:1];
        end else
            raw_sum = sum49_[47:0];
    end

    // Leading-1 detection
    // Leading-1 detection (+1 on addition carry-out for correct exponent)
    lz = leading_one(raw_sum);

    // Normalize
    if (raw_sum == 48'd0)
        norm = 48'd0;
    else
        norm = raw_sum << (7'd47 - lz);

    // Rounding
    case (rnd_mode)
        2'b00: rnd_up = norm[23] & (norm[24] | guard | round_ | sticky_);
        2'b01: rnd_up = 1'b0;
        2'b10: rnd_up =  result_sign & (norm[23] | guard | round_ | sticky_);
        2'b11: rnd_up = ~result_sign & (norm[23] | guard | round_ | sticky_);
        default: rnd_up = 1'b0;
    endcase

    if (rnd_up) begin
        // 49-bit addition to detect carry-out past bit47
        // 49-bit rounding addition (n49_ declared at module level)
        n49_ = {1'b0, norm} + (49'd1 << 24);
        if (n49_[48]) begin
            // Carry out: mantissa overflowed ? shift right 1, exponent +1
            // lz increments by 1 (not set to 47) to avoid double-counting
            norm = n49_[48:1];
            lz   = lz + 8'd1;
        end else begin
            norm = n49_[47:0];
            lz   = leading_one(norm);
        end
    end

    // Exponent: products in Q2.46, leading 1 at bit 46 = normal.
    // exp field = exp_base + lz - 46
    exp_out  = exp_base + {1'b0, lz} - 9'd46 + {8'd0, add_carry_};
    mant_out = norm[46:24];

    // Pack
    if (raw_sum == 48'd0)begin
        out = 32'd0;
        done = 1'b1;
        end
    else if (exp_out >= 9'd255) begin
        out = {result_sign, 8'hFF, 23'd0};
        done = 1'b1;
        end
    else if (exp_out[8] || exp_out == 9'd0) begin
        out = 32'd0;
        done = 1'b1;
        end
    else begin
        out = {result_sign, exp_out[7:0], mant_out};
        done = 1'b1;
        end
end

